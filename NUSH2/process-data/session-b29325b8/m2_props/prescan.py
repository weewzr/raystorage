def cp(r, T):
    _, _, a, b, c, d, e, f, g, h = r
    t = T / 1000
    return a + b*t + c*t*t + d*t**3 + e/t/t


def dh(r, T):
    _, _, a, b, c, d, e, f, g, h = r
    t = T / 1000
    return a*t + b*t*t/2 + c*t**3/3 + d*t**4/4 - e/t + f - h


def s(r, T):
    _, _, a, b, c, d, e, f, g, h = r
    t = T / 1000
    return a*math.log(t) + b*t + c*t*t/2 + d*t**3/3 - e/(2*t*t) + g


