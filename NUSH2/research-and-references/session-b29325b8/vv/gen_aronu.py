def meas(tbl, loc, w, T, rows):
    for i, (p, al) in enumerate(rows, 1):
        c = {"w_MEA_mass_pct": w, "T_C": T, "alpha_mol_mol": al}
        a.add(loc, "table", "measured", f"t{tbl}_w{w}_T{T}_m{i}", "pCO2", p, "kPa", c)


def model(tbl, loc, w, T, rows, dup=()):
    for i, (pt, pm, al) in enumerate(rows, 1):
        c = {"w_MEA_mass_pct": w, "T_C": T, "alpha_mol_mol": al}
        if pt in dup:
            c["dup_printed"] = "1"
        s = f"t{tbl}_w{w}_T{T}_h{i}"
        a.add(loc, "table", "measured", s, "Ptot", pt, "kPa", c)
        a.add(loc, "table", "reported_model", s, "pCO2_model", pm, "kPa", c)


